// services/recordingDocx.service.js
// Builds a Word (.docx) document: meeting details, AI notes, then the full timestamped transcript.
//   npm i docx

import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, BorderStyle } from "docx";

const NAVY = "0B1F3A";
const GREEN = "1E7F4F";
const MUTED = "64748B";

const clock = (s) => {
  const t = Math.max(0, Math.floor(Number(s) || 0));
  const h = Math.floor(t / 3600), m = Math.floor((t % 3600) / 60), sec = t % 60;
  const p = (n) => String(n).padStart(2, "0");
  return h ? `${h}:${p(m)}:${p(sec)}` : `${p(m)}:${p(sec)}`;
};

const heading = (text) =>
  new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 320, after: 120 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: GREEN, space: 4 } },
    children: [new TextRun({ text, bold: true, color: NAVY, size: 28 })],
  });

const body = (text) => new Paragraph({ spacing: { after: 120, line: 300 }, children: [new TextRun({ text: String(text || ""), size: 22 })] });
const bullet = (text) => new Paragraph({ bullet: { level: 0 }, spacing: { after: 60 }, children: [new TextRun({ text: String(text || ""), size: 22 })] });
const meta = (label, value) =>
  new Paragraph({ spacing: { after: 40 }, children: [new TextRun({ text: `${label}: `, bold: true, color: MUTED, size: 21 }), new TextRun({ text: String(value ?? "-"), size: 21 })] });

const list = (items, empty) => (items?.length ? items.map(bullet) : [new Paragraph({ children: [new TextRun({ text: empty, italics: true, color: MUTED, size: 21 })] })]);

export const buildRecordingDocx = async ({ session, recording }) => {
  const notes = recording.notes;
  const when = recording.startedAt ? new Date(recording.startedAt).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short", timeZone: "Africa/Lagos" }) : "-";
  const mins = recording.durationSeconds ? `${Math.round(recording.durationSeconds / 60)} min` : "-";

  const children = [
    new Paragraph({ children: [new TextRun({ text: "GIEVA", bold: true, color: GREEN, size: 24 })] }),
    new Paragraph({ heading: HeadingLevel.TITLE, spacing: { after: 160 }, children: [new TextRun({ text: session.title || "Live session", bold: true, color: NAVY, size: 44 })] }),
    meta("Date", when),
    meta("Duration", mins),
  ];

  if (notes) {
    children.push(heading("Summary"), body(notes.summary || "-"));
    children.push(heading("Key points"), ...list(notes.keyPoints, "None"));
    children.push(heading("Decisions"), ...list(notes.decisions, "No decisions recorded"));
    children.push(heading("Action items"), ...list((notes.actionItems || []).map((a) => (a.owner ? `${a.task} (${a.owner})` : a.task)), "None"));
    children.push(heading("Open questions"), ...list(notes.openQuestions, "None"));
    children.push(new Paragraph({ spacing: { before: 120 }, children: [new TextRun({ text: "Notes were generated by AI from an automatic transcript. Check names, numbers and decisions before sharing.", italics: true, color: MUTED, size: 18 })] }));
  }

  children.push(heading("Full transcript"));
  const segs = recording.transcriptSegments?.length ? recording.transcriptSegments : [{ start: null, text: recording.transcript || "" }];
  segs.forEach((s) => {
    children.push(
      new Paragraph({
        spacing: { after: 100, line: 300 },
        children: [
          ...(s.start !== null && s.start !== undefined ? [new TextRun({ text: `[${clock(s.start)}]  `, bold: true, color: MUTED, size: 20, font: "Consolas" })] : []),
          new TextRun({ text: String(s.text || "").trim(), size: 22 }),
        ],
      })
    );
  });

  const doc = new Document({
    creator: "GIEVA",
    title: session.title || "Live session transcript",
    styles: { default: { document: { run: { font: "Calibri" } } } },
    sections: [{ properties: { page: { margin: { top: 1000, bottom: 1000, left: 1100, right: 1100 } } }, children }],
  });
  return Packer.toBuffer(doc);
};
